import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = path.join(root, "docs", "feature-tree", "data");
const commitsFile = path.join(dataDir, "commits.js");
const archiveRefs = ["origin/backup/pre-revert-7daf5e7", "feat/ui-redesign-audit"];
const checkOnly = process.argv.includes("--check");

const KINDS = new Set([
  "app",
  "screen",
  "subscreen",
  "card",
  "component",
  "overlay",
  "modal",
  "state",
  "logic",
  "service",
  "data",
  "table",
  "config",
  "group",
  "archive",
]);
const STATUSES = new Set(["active", "placeholder", "planned", "removed", "reverted"]);
const GROUP_KINDS = new Set(["group", "archive"]);
const DATE = /^(\d{4}-\d{2}-\d{2}) (\d{2}:\d{2}) ([+-]\d{2})(\d{2})$/;
const ID = /^[a-z0-9]+(-[a-z0-9]+)*$/;

const errors = [];
const warnings = [];

function git(args) {
  return execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
}

function refExists(ref) {
  try {
    git(["rev-parse", "--verify", "--quiet", ref]);
    return true;
  } catch {
    return false;
  }
}

function readCommits(range, lineage, into) {
  const out = git([
    "log",
    "--reverse",
    "--abbrev=7",
    "--date=format:%Y-%m-%d %H:%M %z",
    "--name-status",
    "--pretty=format:@@%h%x09%ad%x09%s",
    range,
  ]);
  let current = null;
  for (const line of out.split(/\r?\n/)) {
    if (line.startsWith("@@")) {
      const [hash, date, ...subject] = line.slice(2).split("\t");
      current = into[hash] ? null : { d: date, s: subject.join("\t"), l: lineage, f: [] };
      if (current) into[hash] = current;
      continue;
    }
    if (!current || !line.trim()) continue;
    const [status, ...paths] = line.split("\t");
    current.f.push(`${status.charAt(0)} ${paths.join(" → ")}`);
  }
}

function formatNow() {
  const now = new Date();
  const pad = (value) => String(value).padStart(2, "0");
  const offset = -now.getTimezoneOffset();
  const sign = offset >= 0 ? "+" : "-";
  const tz = `${sign}${pad(Math.floor(Math.abs(offset) / 60))}${pad(Math.abs(offset) % 60)}`;
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ${pad(now.getHours())}:${pad(now.getMinutes())} ${tz}`;
}

function generateCommits() {
  const commits = {};
  readCommits("HEAD", "main", commits);
  for (const ref of archiveRefs) {
    if (refExists(ref)) readCommits(`HEAD..${ref}`, "reverted", commits);
  }
  const repo = git(["remote", "get-url", "origin"]).trim().replace(/\.git$/, "");
  const rows = Object.entries(commits).map(([hash, commit]) => `  ${JSON.stringify(hash)}: ${JSON.stringify(commit)},`);
  const source = [
    "// Generated by scripts/feature-tree.mjs from git history. Regenerate it instead of editing by hand.",
    `CAPS.repo = ${JSON.stringify(repo)};`,
    `CAPS.generated = ${JSON.stringify(formatNow())};`,
    "CAPS.commits = {",
    ...rows,
    "};",
    "",
  ].join("\n");
  fs.writeFileSync(commitsFile, source);
  return Object.keys(commits).length;
}

function toEpoch(date) {
  const match = DATE.exec(date);
  return match ? Date.parse(`${match[1]}T${match[2]}:00${match[3]}:${match[4]}`) : NaN;
}

function loadSite() {
  const sandbox = { CAPS: { trees: {} } };
  sandbox.window = sandbox;
  vm.createContext(sandbox);
  const files = fs.readdirSync(dataDir).filter((file) => file.endsWith(".js"));
  for (const file of ["commits.js", ...files.filter((name) => name !== "commits.js").sort()]) {
    const full = path.join(dataDir, file);
    if (!fs.existsSync(full)) {
      errors.push(`${file}: missing (run without --check to generate it)`);
      continue;
    }
    try {
      vm.runInContext(fs.readFileSync(full, "utf8"), sandbox, { filename: full });
    } catch (error) {
      errors.push(`${file}: ${error.message}`);
    }
    const id = file.replace(/\.js$/, "");
    if (file !== "commits.js" && !sandbox.CAPS.trees[id]) {
      errors.push(`${file}: must assign CAPS.trees[${JSON.stringify(id)}]`);
    }
  }
  return sandbox.CAPS;
}

function collect(tree) {
  const nodes = new Map();
  const walk = (node, trail) => {
    const label = `${tree.id} › ${[...trail, node?.id ?? "?"].join(" › ")}`;
    if (!node || typeof node !== "object") {
      errors.push(`${label}: node is not an object`);
      return;
    }
    if (!ID.test(node.id ?? "")) errors.push(`${label}: id must be kebab-case`);
    if (nodes.has(node.id)) errors.push(`${label}: duplicate id in tree`);
    nodes.set(node.id, { node, label });
    for (const child of node.children ?? []) walk(child, [...trail, node.id]);
  };
  walk(tree.root, []);
  return nodes;
}

function resolve(site, treeId, target) {
  const [targetTree, targetId] = target.includes(":") ? target.split(":") : [treeId, target];
  return site.index.get(targetTree)?.get(targetId)?.node;
}

function checkNode(site, tree, node, label, referenced) {
  if (node.ref) {
    if (!resolve(site, tree.id, node.ref)) errors.push(`${label}: ref "${node.ref}" does not resolve`);
    if (node.versions?.length || node.children?.length) errors.push(`${label}: ref nodes cannot have versions or children`);
    return;
  }
  if (!node.title) errors.push(`${label}: missing title`);
  if (!KINDS.has(node.kind)) errors.push(`${label}: unknown kind "${node.kind}"`);
  if (node.status && !STATUSES.has(node.status)) errors.push(`${label}: unknown status "${node.status}"`);
  if (!node.summary) errors.push(`${label}: missing summary`);
  if (!node.tagline) warnings.push(`${label}: missing tagline`);
  for (const link of node.links ?? []) {
    if (!resolve(site, tree.id, link)) warnings.push(`${label}: link "${link}" does not resolve`);
  }
  const versions = node.versions ?? [];
  if (!versions.length && !GROUP_KINDS.has(node.kind)) errors.push(`${label}: needs at least one version`);
  let previous = -Infinity;
  const seen = new Set();
  versions.forEach((version, index) => {
    const where = `${label} v${version.n ?? "?"}`;
    if (version.n !== index + 1) errors.push(`${where}: versions must be numbered 1..n in order`);
    if (!version.name) errors.push(`${where}: missing name`);
    if (!version.changes?.length) errors.push(`${where}: missing changes`);
    const epoch = toEpoch(version.date ?? "");
    if (Number.isNaN(epoch)) errors.push(`${where}: date must look like "2026-10-03 22:31 -0400"`);
    if (epoch < previous) warnings.push(`${where}: earlier than the previous version`);
    previous = epoch;
    const commits = version.commits ?? [];
    if (!commits.length && !version.uncommitted) errors.push(`${where}: list commits or set uncommitted: true`);
    let latest = -Infinity;
    for (const hash of commits) {
      const commit = site.commits[hash];
      if (!commit) {
        errors.push(`${where}: unknown commit ${hash} (use 7-character hashes from data/commits.js)`);
        continue;
      }
      if (seen.has(hash)) warnings.push(`${where}: commit ${hash} already used by an earlier version of this node`);
      seen.add(hash);
      referenced.add(hash);
      latest = Math.max(latest, toEpoch(commit.d));
    }
    if (commits.length && Number.isFinite(latest) && latest !== epoch) {
      warnings.push(`${where}: date should match its latest commit (${new Date(latest).toISOString()})`);
    }
  });
}

if (!checkOnly) console.log(`commits.js: ${generateCommits()} commits`);

const site = loadSite();
site.index = new Map();
const trees = Object.values(site.trees ?? {});
for (const tree of trees) {
  if (!tree.title || !tree.summary || !tree.root) errors.push(`${tree.id}: tree needs title, summary, and root`);
  else site.index.set(tree.id, collect(tree));
}

const referenced = new Set();
for (const tree of trees) {
  for (const { node, label } of site.index.get(tree.id)?.values() ?? []) {
    checkNode(site, tree, node, label, referenced);
  }
}

const unmapped = (lineage) =>
  Object.entries(site.commits ?? {}).filter(([hash, commit]) => commit.l === lineage && !referenced.has(hash));
for (const [hash, commit] of unmapped("main")) warnings.push(`unmapped main commit ${hash} ${commit.d} ${commit.s}`);
const unmappedReverted = unmapped("reverted");

for (const tree of trees) {
  const nodes = [...(site.index.get(tree.id)?.values() ?? [])];
  const versions = nodes.reduce((sum, { node }) => sum + (node.versions?.length ?? 0), 0);
  console.log(`${tree.id}: ${nodes.length} nodes, ${versions} versions`);
}
if (unmappedReverted.length) {
  console.log(`\n${unmappedReverted.length} reverted-lineage commits are not mapped to a version:`);
  for (const [hash, commit] of unmappedReverted) console.log(`  ${hash} ${commit.d} ${commit.s}`);
}
if (warnings.length) {
  console.log(`\n${warnings.length} warning(s):`);
  for (const warning of warnings) console.log(`  ${warning}`);
}
if (errors.length) {
  console.log(`\n${errors.length} error(s):`);
  for (const error of errors) console.log(`  ${error}`);
  process.exit(1);
}
console.log("\nFeature tree data is valid.");
